#!/usr/bin/env python3
"""Give a vinny worktree its own `node_modules` in seconds instead of a full `yarn install`.

The obvious shortcut — symlinking `node_modules` from another worktree — is wrong, and quietly so.
Yarn workspaces install `node_modules/@vinny/<pkg>` as a *relative* symlink to `../../libs/<pkg>`.
Resolve that through a borrowed `node_modules` and the `..` walks out of the donor's real path, so
every `@vinny/*` import lands on the DONOR worktree's branch. Two agents editing `libs/` then
typecheck and test against each other's code, and nothing warns you.

This builds a real `node_modules` directory instead:

  * third-party packages  -> symlink to the donor's copy (shared, nobody edits them)
  * workspace packages    -> the SAME relative target, recreated locally, so `../../libs/<pkg>`
                             resolves inside THIS worktree

Workspace packages are detected by their symlink target, not by an allowlist, so extra workspace
roots (`apps/*`, `testing/*`, `tools/*`, `libs/mongo-schemas/*`, ...) are picked up automatically.

  ./link_worktree_node_modules.py ~/src/vinny-worktrees/my-branch
  ./link_worktree_node_modules.py ~/src/vinny-worktrees/my-branch --donor ~/src/vinny-worktrees/other
  ./link_worktree_node_modules.py ~/src/vinny-worktrees/my-branch --check
"""
import argparse
import logging
import os
import sys
from pathlib import Path

WORKSPACE_HINTS = ("libs/", "apps/", "testing/", "tools/")
# Verified after a build: these must resolve inside the target worktree, not the donor.
CANARY_PACKAGES = ("data-collection-types", "data-collection-utils", "mongo-schema-data-collection")

logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
log = logging.getLogger(__name__)


def is_workspace_link(entry: Path) -> bool:
    """A workspace package is a relative symlink pointing back into the repo's source tree."""
    if not entry.is_symlink():
        return False
    target = os.readlink(entry)
    return not os.path.isabs(target) and any(hint in target for hint in WORKSPACE_HINTS)


def link_entry(source: Path, dest: Path) -> str:
    """Recreate one node_modules entry. Returns 'workspace', 'external' or 'skipped'."""
    if dest.is_symlink() or dest.exists():
        return "skipped"
    if is_workspace_link(source):
        # Same relative target, new anchor: now it resolves inside this worktree.
        dest.symlink_to(os.readlink(source))
        return "workspace"
    dest.symlink_to(source)
    return "external"


def build(target: Path, donor_modules: Path) -> dict[str, int]:
    """Replace the target's node_modules with a real directory of per-entry symlinks."""
    modules = target / "node_modules"
    if modules.is_symlink():
        log.info("removing the borrowed node_modules symlink -> %s", os.readlink(modules))
        modules.unlink()
    modules.mkdir(exist_ok=True)

    counts = {"workspace": 0, "external": 0, "skipped": 0}
    for entry in donor_modules.iterdir():
        if entry.name.startswith("@"):
            (modules / entry.name).mkdir(exist_ok=True)
            for scoped in entry.iterdir():
                counts[link_entry(scoped, modules / entry.name / scoped.name)] += 1
        else:
            counts[link_entry(entry, modules / entry.name)] += 1
    return counts


def check(target: Path) -> bool:
    """Confirm the canary workspace packages resolve inside this worktree."""
    ok = True
    for name in CANARY_PACKAGES:
        link = target / "node_modules" / "@vinny" / name
        if not link.exists():
            log.error("%s is missing", name)
            ok = False
            continue
        resolved = link.resolve()
        inside = resolved.is_relative_to(target.resolve())
        log.info("%-32s -> %s %s", name, resolved, "OK" if inside else "WRONG WORKTREE")
        ok = ok and inside
    return ok


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("worktree", type=Path, help="the worktree to give a node_modules to")
    parser.add_argument(
        "--donor",
        type=Path,
        help="a worktree that already has a real node_modules (default: the first sibling that does)",
    )
    parser.add_argument("--check", action="store_true", help="only verify an existing node_modules")
    args = parser.parse_args()

    target = args.worktree.expanduser().resolve()
    if not (target / "package.json").is_file():
        sys.exit(f"{target} does not look like a vinny worktree (no package.json)")

    if args.check:
        sys.exit(0 if check(target) else "workspace packages resolve outside this worktree")

    donor = args.donor.expanduser().resolve() if args.donor else find_donor(target)
    donor_modules = donor / "node_modules"
    if not donor_modules.is_dir() or donor_modules.is_symlink():
        sys.exit(f"{donor} has no real node_modules to copy links from")

    counts = build(target, donor_modules)
    log.info(
        "linked %d workspace + %d external packages (%d already present)",
        counts["workspace"],
        counts["external"],
        counts["skipped"],
    )
    if not check(target):
        sys.exit("build finished but workspace packages resolve outside the worktree")


def find_donor(target: Path) -> Path:
    """The first sibling worktree with a real node_modules directory."""
    for sibling in sorted(target.parent.iterdir()):
        if sibling == target:
            continue
        modules = sibling / "node_modules"
        if modules.is_dir() and not modules.is_symlink() and (sibling / "package.json").is_file():
            log.info("using %s as the donor", sibling.name)
            return sibling
    sys.exit("no sibling worktree has a real node_modules — run `yarn install` in one first")


if __name__ == "__main__":
    main()
